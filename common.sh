#!/usr/bin/env bash

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE_DEFAULT="${PROJECT_DIR}/configs/default.env"

die() {
  echo "Error: $*" >&2
  exit 1
}

require_apple_silicon_mac() {
  [[ "$(uname -s)" == "Darwin" ]] || die "This project supports macOS only."
  [[ "$(uname -m)" == "arm64" ]] || die "This project supports Apple Silicon (arm64) only."

  local major
  major=$(sw_vers -productVersion | cut -d. -f1)
  [[ "${major}" =~ ^[0-9]+$ ]] || die "Unable to detect the macOS version."
  (( major >= 26 )) || die "Apple container requires macOS 26 or newer."
}

require_container_cli() {
  command -v container >/dev/null 2>&1 || die "Apple container is not installed. Run: ./install-container.sh"
}

require_container_system() {
  container system status >/dev/null 2>&1 || die "Apple container services are not running. Run: ./container-service.sh start"
}

load_config() {
  local config_file="${1:-${CONFIG_FILE_DEFAULT}}"
  [[ -f "${config_file}" ]] || die "Configuration not found: ${config_file}. Run ./configure.sh first."
  # This is a project-local shell configuration file generated by configure.sh.
  # shellcheck source=/dev/null
  source "${config_file}"

  : "${CONTAINER_NAME:?Missing CONTAINER_NAME}"
  : "${IMAGE_NAME:?Missing IMAGE_NAME}"
  : "${CONFIG_VOLUME:?Missing CONFIG_VOLUME}"
  : "${RESOLUTION:?Missing RESOLUTION}"
  : "${DPI:?Missing DPI}"
  : "${STREAM_SCALE:?Missing STREAM_SCALE}"
  : "${FRAMERATE:?Missing FRAMERATE}"
  : "${TIMEZONE:?Missing TIMEZONE}"
  : "${HTTP_PORT:?Missing HTTP_PORT}"
  : "${HTTPS_PORT:?Missing HTTPS_PORT}"
  : "${CPUS:?Missing CPUS}"
  : "${MEMORY:?Missing MEMORY}"
  : "${BUILD_CPUS:?Missing BUILD_CPUS}"
  : "${BUILD_MEMORY:?Missing BUILD_MEMORY}"
  : "${SHM_SIZE:?Missing SHM_SIZE}"

  # Use English language and keyboard defaults for older configuration files.
  UBUNTU_VERSION=${UBUNTU_VERSION:-24.04}
  BASE_IMAGE=${BASE_IMAGE:-ghcr.io/tatsuyai713/webtop-kde-base-arm64-u${UBUNTU_VERSION}:1.1.0}
  [[ "${UBUNTU_VERSION}" == "22.04" || "${UBUNTU_VERSION}" == "24.04" || "${UBUNTU_VERSION}" == "26.04" ]] || die "UBUNTU_VERSION must be 22.04, 24.04, or 26.04."
  USER_LANGUAGE=${USER_LANGUAGE:-en}
  [[ "${USER_LANGUAGE}" == "ja" ]] && USER_LANGUAGE=jp
  [[ "${USER_LANGUAGE}" == "en" || "${USER_LANGUAGE}" == "jp" ]] || die "USER_LANGUAGE must be en or jp."
  KEYBOARD_LAYOUT=${KEYBOARD_LAYOUT:-us}
  [[ "${KEYBOARD_LAYOUT}" == "us" || "${KEYBOARD_LAYOUT}" == "jp" ]] || die "KEYBOARD_LAYOUT must be us or jp."
  INSTALL_ROS2=${INSTALL_ROS2:-true}
  INSTALL_DEV_TOOLS=${INSTALL_DEV_TOOLS:-true}
  ENABLE_XRDP=${ENABLE_XRDP:-true}
  RDP_PORT=${RDP_PORT:-3389}
  FOXGLOVE_PORT=${FOXGLOVE_PORT:-8765}
  ROSBRIDGE_PORT=${ROSBRIDGE_PORT:-9090}
  [[ "${INSTALL_ROS2}" == "true" || "${INSTALL_ROS2}" == "false" ]] || die "INSTALL_ROS2 must be true or false."
  [[ "${INSTALL_DEV_TOOLS}" == "true" || "${INSTALL_DEV_TOOLS}" == "false" ]] || die "INSTALL_DEV_TOOLS must be true or false."
  [[ "${ENABLE_XRDP}" == "true" || "${ENABLE_XRDP}" == "false" ]] || die "ENABLE_XRDP must be true or false."
  MOUNT_HOME=${MOUNT_HOME:-true}
  MOUNT_SSH=${MOUNT_SSH:-true}
  SSL_DIR=${SSL_DIR:-}
}

ensure_config() {
  local config_file="${1:-${CONFIG_FILE_DEFAULT}}"
  [[ -f "${config_file}" ]] && return 0

  [[ -t 0 ]] || die "Configuration not found: ${config_file}. Run ./configure.sh --config ${config_file} first."
  echo "No configuration found at: ${config_file}"
  echo "Running the container configuration wizard before continuing..."
  "${PROJECT_DIR}/configure.sh" --config "${config_file}"
}

container_exists() {
  container inspect "$1" >/dev/null 2>&1
}

image_exists() {
  container image inspect "$1" >/dev/null 2>&1
}

volume_exists() {
  container volume inspect "$1" >/dev/null 2>&1
}

calculate_scale() {
  awk -v dpi="$1" 'BEGIN { printf "%.2f", dpi / 96 }'
}

detect_host_timezone() {
  local timezone_path timezone
  timezone_path=$(readlink /etc/localtime 2>/dev/null || true)
  if [[ "${timezone_path}" == *"/zoneinfo/"* ]]; then
    timezone=${timezone_path#*"/zoneinfo/"}
    [[ -n "${timezone}" ]] && { printf '%s\n' "${timezone}"; return 0; }
  fi

  if [[ -r /etc/timezone ]]; then
    IFS= read -r timezone < /etc/timezone || true
    [[ -n "${timezone}" ]] && { printf '%s\n' "${timezone}"; return 0; }
  fi

  printf '%s\n' UTC
}


# Runtime commands share the same environment/config-file selection as start.
ACTIVE_CONFIG_FILE=${ACTIVE_CONFIG_FILE:-${PROJECT_DIR}/configs/.last-used-config}

config_container_exists() {
  (
    source "$1"
    [[ -n "${CONTAINER_NAME:-}" ]] && container_exists "${CONTAINER_NAME}"
  )
}

container_is_running() {
  local inspection
  inspection=$(container inspect "$1" 2>/dev/null) || return 1
  printf '%s\n' "${inspection}" | python3 -c '
import json,sys
try:
    records=json.load(sys.stdin)
    running=any(r["id"]==sys.argv[1] and r["status"]["state"]=="running" for r in records)
except (ValueError,KeyError,TypeError):
    running=False
sys.exit(0 if running else 1)
' "$1"
}

remember_runtime_config() {
  local absolute
  absolute="$(cd "$(dirname "${CONFIG_FILE}")" && pwd)/$(basename "${CONFIG_FILE}")"
  mkdir -p "$(dirname "${ACTIVE_CONFIG_FILE}")"
  printf '%s\n' "${absolute}" > "${ACTIVE_CONFIG_FILE}.tmp.$$"
  chmod 600 "${ACTIVE_CONFIG_FILE}.tmp.$$"
  mv "${ACTIVE_CONFIG_FILE}.tmp.$$" "${ACTIVE_CONFIG_FILE}"
}

runtime_options() {
  local action=$1
  shift
  CONFIG_FILE_EXPLICIT=false
  [[ -z "${CONFIG_FILE:-}" ]] || CONFIG_FILE_EXPLICIT=true
  CONFIG_FILE=${CONFIG_FILE:-${CONFIG_FILE_DEFAULT}}
  CONFIG_DIRECTORY=${CONTAINER_CONFIG_DIR:-${START_CONFIG_DIR:-${PROJECT_DIR}/configs}}
  NON_INTERACTIVE=false
  DELETE=false
  DELETE_VOLUME=false
  ASSUME_YES=false
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --config)
        [[ $# -ge 2 ]] || die "--config requires a path."
        CONFIG_FILE=$2; CONFIG_FILE_EXPLICIT=true; shift 2 ;;
      --non-interactive) NON_INTERACTIVE=true; shift ;;
      --delete)
        [[ "${action}" == "stop" ]] || die "Unknown option: $1"
        DELETE=true; shift ;;
      --volume)
        [[ "${action}" == "delete" ]] || die "Unknown option: $1"
        DELETE_VOLUME=true; shift ;;
      --yes)
        [[ "${action}" == "delete" ]] || die "Unknown option: $1"
        ASSUME_YES=true; shift ;;
      -h|--help)
        echo "Usage: ./${action}.sh [--config path] [--non-interactive]"
        [[ "${action}" != "stop" ]] || echo "  --delete  Also delete the stopped container; keep its image and volume"
        [[ "${action}" != "delete" ]] || echo "  --volume  Also delete /config volume; --yes skips the deletion confirmation"
        echo "Without --config, use the last started configuration, or select an existing environment."
        exit 0 ;;
      *) die "Unknown option: $1" ;;
    esac
  done
}

load_runtime_config() {
  require_apple_silicon_mac
  require_container_cli
  require_container_system
  if [[ "${CONFIG_FILE_EXPLICIT}" != "true" ]]; then
    select_config_file runtime
  fi
  load_config "${CONFIG_FILE}"
  echo "Using Ubuntu ${UBUNTU_VERSION}: ${CONTAINER_NAME} (${CONFIG_FILE})"
}

config_summary() {
  local config_file=$1
  (
    UBUNTU_VERSION=unknown
    CONTAINER_NAME=unknown
    IMAGE_NAME=unknown
    # This is a project-local shell configuration file generated by configure.sh.
    # shellcheck source=/dev/null
    source "${config_file}"
    printf 'Ubuntu %s, container %s, image %s' \
      "${UBUNTU_VERSION}" "${CONTAINER_NAME}" "${IMAGE_NAME}"
  )
}

select_config_file() {
  local selection_mode=${1:-start}
  local candidate summary selection index last
  local -a existing=()
  local -a candidates=()

  if [[ "${selection_mode}" == "runtime" && -f "${ACTIVE_CONFIG_FILE}" ]]; then
    IFS= read -r last < "${ACTIVE_CONFIG_FILE}" || true
    if [[ -n "${last}" && -f "${last}" ]]; then
      CONFIG_FILE=${last}
      return
    fi
  fi
  shopt -s nullglob
  for candidate in "${CONFIG_DIRECTORY}"/*.env; do
    [[ "$(basename "${candidate}")" == "example.env" ]] && continue
    candidates+=("${candidate}")
  done
  shopt -u nullglob

  if [[ "${selection_mode}" == "runtime" ]] && (( ${#candidates[@]} > 0 )); then
    for candidate in "${candidates[@]}"; do
      if config_container_exists "${candidate}"; then
        existing+=("${candidate}")
      fi
    done
    if (( ${#existing[@]} == 1 )); then
      CONFIG_FILE=${existing[0]}
      return
    fi
    if (( ${#existing[@]} > 1 )); then
      candidates=("${existing[@]}")
    fi
  fi
  if (( ${#candidates[@]} == 0 )); then
    return
  fi
  if (( ${#candidates[@]} == 1 )); then
    CONFIG_FILE=${candidates[0]}
    return
  fi
  if [[ "${NON_INTERACTIVE}" == "true" ]]; then
    die "Multiple configurations found in ${CONFIG_DIRECTORY}. Select one with --config path."
  fi
  [[ -t 0 ]] || die "Multiple configurations found in ${CONFIG_DIRECTORY}. Select one with --config path."

  echo "Available container configurations:"
  for (( index=0; index<${#candidates[@]}; index++ )); do
    candidate=${candidates[index]}
    if ! summary=$(config_summary "${candidate}" 2>/dev/null); then
      summary="invalid configuration"
    fi
    printf '  %d) %s (%s)\n' "$((index + 1))" "$(basename "${candidate}")" "${summary}"
  done

  while true; do
    read -r -p "Select configuration [1-${#candidates[@]}]: " selection || die "Configuration selection was cancelled."
    if [[ "${selection}" =~ ^[0-9]+$ ]] && \
       (( 10#${selection} >= 1 && 10#${selection} <= ${#candidates[@]} )); then
      CONFIG_FILE=${candidates[10#${selection} - 1]}
      echo "Selected configuration: ${CONFIG_FILE}"
      return
    fi
    echo "Enter a number from 1 to ${#candidates[@]}." >&2
  done
}
